/**
 * @file sigmoid.h
 * @brief Заголовочный файл для планировщика скорости на основе сигмоиды.
 *
 * Реализует плавное изменение скорости с использованием логистической функции.
 * Поддерживает "мертвую зону" (v_jump) для компенсации трения покоя.
 */
#ifndef SIGMOID_H
#define SIGMOID_H

#include <stdint.h>
#include "../../Core/Inc/stepper_planner.h"

/**
 * @brief Структура состояния планировщика на основе сигмоиды.
 */
typedef struct {
    StepperPlanner_t base;  ///< Базовый интерфейс (должен быть первым полем!)

    int32_t v0;             ///< Начальная скорость
    int32_t v1;             ///< Целевая скорость
    int32_t dv;             ///< Разность скоростей (v1 - v0)

    uint16_t v_jump;        ///< Порог "мертвой зоны" (мин. скорость для преодоления трения)
    float t_jump;           ///< Время выхода из "мертвой зоны"
    float k_jump;           ///< Коэффициент формы перехода в "мертвой зоне"

    uint32_t a;             ///< Максимальное ускорение
    float k;                ///< Коэффициент крутизны сигмоиды
    float t0;               ///< Время достижения середины перехода (центр сигмоиды)
    float eps;              ///< Точность (малое значение для вычисления границ)
} Sigmoid_t;

/// Экземпляр интерфейса для планировщика на основе сигмоиды
extern const StepperPlanner_Interface Sigmoid_Itf;

#endif // SIGMOID_H
