/**
 * @file linear.h
 * @brief Заголовочный файл для линейного планировщика скорости.
 *
 * Реализует простейший профиль скорости с постоянным ускорением (трапецеидальный
 * профиль без участков постоянной скорости — только разгон/торможение).
 * Скорость изменяется по линейному закону: v(t) = v0 + slope * t.
 */
#ifndef LINEAR_H
#define LINEAR_H

#include <stdint.h>
#include "../../Core/Inc/stepper_planner.h"

/**
 * @brief Структура состояния линейного планировщика.
 *
 * Содержит параметры линейного закона изменения скорости:
 * начальную/целевую скорость, ускорение, время перехода и наклон.
 */
typedef struct {
    StepperPlanner_t base;  ///< Базовый интерфейс

    int32_t  v0;            ///< Начальная скорость (шагов/с)
    int32_t  v1;            ///< Целевая скорость (шагов/с)
    uint16_t v_jump;        ///< Порог "мертвой зоны" (компенсация трения покоя)
    uint32_t a;             ///< Модуль ускорения (шагов/с^2)
    float    t;             ///< Полное время разгона/торможения (мс)
    float    slope;         ///< Наклон скорости (dv / t), шаг/мс
    int32_t  dv;            ///< Разность скоростей (v1 - v0)
} Linear_t;

/// Экземпляр интерфейса для линейного планировщика
extern const StepperPlanner_Interface Linear_Itf;

#endif // LINEAR_H
