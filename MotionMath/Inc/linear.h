#ifndef LINEAR_H
#define LINEAR_H

#include <stdint.h>

#include "planner.h"

/**
@brief Структура линейной кривой для планирования движения
Реализует профиль скорости с постоянным ускорением: v(t) = v0 + (v1 - v0) / T * t
Обеспечивает максимально быстрый разгон/торможение при заданном ускорении.
*/
typedef struct {
    int32_t v0;        /**< Начальная скорость (импульсов/сек) */
    int32_t v1;        /**< Конечная скорость (импульсов/сек) */

    uint16_t v_jump;   /**< Минимальная скорость (прыжок от нуля) */
    uint32_t a;        /**< Ускорение (импульсов/сек²) */

    float t;           /**< Полное время разгона (мс) */
    float slope;       /**< Наклон (изменение скорости за 1 мс) */
    int32_t dv;        /**< Разность скоростей (v1 - v0) */
} Linear_t;

extern const Planner_Interface Linear_Itf;

#endif
