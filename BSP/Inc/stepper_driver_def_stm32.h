/**
 * @file stepper_driver_def_stm32.h
 * @brief Определения констант для драйвера шагового двигателя на STM32.
 *
 * Содержит макросы, используемые в аппаратно-зависимой реализации драйвера
 * (stepper_driver_stm32.c) для:
 *   - идентификации каналов таймера (1..4);
 *   - указания разрядности таймера (16 или 32 бита);
 *   - задания минимально допустимой тактовой частоты шины APB.
 */
#ifndef STEPPER_DRIVER_DEF_STM32F4_H
#define STEPPER_DRIVER_DEF_STM32F4_H

/** @name Идентификаторы каналов таймера
 *  Используются для выбора активного канала PWM в структуре StepperDriverSTM32_t.
 *  @{
 */
#define TIM_CHAN_1      0x01  ///< Канал 1 таймера (CCR1, CCER_CC1E, CCMR1_OC1*)
#define TIM_CHAN_2      0x02  ///< Канал 2 таймера (CCR2, CCER_CC2E, CCMR1_OC2*)
#define TIM_CHAN_3      0x03  ///< Канал 3 таймера (CCR3, CCER_CC3E, CCMR2_OC3*)
#define TIM_CHAN_4      0x04  ///< Канал 4 таймера (CCR4, CCER_CC4E, CCMR2_OC4*)
/** @} */

/** @name Разрядность таймера
 *  Определяет максимальное значение регистра ARR (Auto-Reload Register).
 *  Используется в функции StepperDriverSTM32_CanSetVel() для проверки
 *  достижимости заданной скорости.
 *  @{
 */
#define TIM_16_BIT      16    ///< 16-битный таймер (макс. ARR = 65535)
#define TIM_32_BIT      32    ///< 32-битный таймер (макс. ARR = 4294967295)
/** @} */

/**
 * @brief Минимально допустимая тактовая частота шины APB (Гц).
 *
 * Используется в StepperDriverSTM32_Init() для проверки корректности
 * конфигурации таймера. Если частота ниже этого порога, инициализация
 * прерывается (возврат из функции без настройки периферии).
 *
 * @note Значение 20000 Гц (20 кГц) выбрано как разумный минимум для
 *       обеспечения точного управления скоростью шагового двигателя.
 */
#define MIN_CLK_APB     20000

#endif // STEPPER_DRIVER_DEF_STM32F4_H
