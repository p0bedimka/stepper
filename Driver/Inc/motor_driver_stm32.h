#ifndef MOTOR_DRIVER_STM32_H
#define MOTOR_DRIVER_STM32_H

#include <stdbool.h>
#include <stdint.h>

#include "stm32f4xx.h"

#include "motor_driver_def_stm32.h"

/**
 * @brief Структура конфигурации драйвера для STM32
 *
 * Содержит все необходимые настройки для управления таймером
 * и выводами шагового двигателя на микроконтроллерах STM32.
 */
typedef struct {
    /**
     * @brief Конфигурация таймера
     */
    struct {
        TIM_TypeDef *Instance;  /**< Указатель на регистры таймера (например, TIM1) */
        uint8_t Channel;        /**< Номер канала таймера (1-4) */
        uint8_t Bit;            /**< Разрядность таймера: TIM_16_BIT или TIM_32_BIT */
        uint32_t Clock;         /**< Частота тактирования таймера в Гц */
        IRQn_Type IRQn;         /**< Номер прерывания таймера (например, TIM1_UP_IRQn) */
    } htim;

    /**
     * @brief Конфигурация вывода направления
     */
    struct {
        GPIO_TypeDef *Port;     /**< Порт GPIO для управления направлением */
        uint16_t Pin;           /**< Номер пина (GPIO_Pin_x) */
        uint32_t State;         /**< Текущее состояние (BSRR значение для установки) */
    } dir;

    /**
     * @brief Конфигурация вывода разрешения (Enable)
     */
    struct {
        GPIO_TypeDef *Port;     /**< Порт GPIO для управления разрешением */
        uint16_t Pin;           /**< Номер пина (GPIO_Pin_x) */
    } en;

    /**
     * @brief Функция получения текущего времени в микросекундах
     * @return Текущее время (мкс)
     *
     * Должна возвращать монотонно возрастающее значение.
     * Используется планировщиком для расчёта интервалов.
     */
    uint32_t (*GetTick)(void);
} MotorDriver_Type;

/* ============ Прототипы функций ============ */

/**
 * @brief Инициализация драйвера
 * @param dr Указатель на структуру драйвера
 *
 * Проверяет корректность всех параметров конфигурации.
 * Настраивает таймер в режим ШИМ с периодом ~1000 Гц по умолчанию.
 */
void MotorDriver_Init(MotorDriver_Type *dr);

/**
 * @brief Включение драйвера
 * @param dr Указатель на структуру драйвера
 *
 * Запускает таймер, включает выход сравнения, активирует вывод Enable.
 * Разрешает прерывания таймера.
 */
void MotorDriver_Enable(MotorDriver_Type *dr);

/**
 * @brief Отключение драйвера
 * @param dr Указатель на структуру драйвера
 *
 * Останавливает таймер, отключает выход сравнения.
 * Деактивирует вывод Enable и запрещает прерывания.
 */
void MotorDriver_Disable(MotorDriver_Type *dr);

/**
 * @brief Проверка возможности установки скорости
 * @param dr Указатель на структуру драйвера
 * @param freq Запрашиваемая частота (импульсов/сек)
 * @return true - частота достижима, false - слишком высокая
 */
bool MotorDriver_СanSetVel(MotorDriver_Type *dr, int32_t freq);

/**
 * @brief Установка скорости
 * @param dr Указатель на структуру драйвера
 * @param vel Скорость (имп/сек). Отрицательная - обратное направление.
 * @return true - успешно, false - ошибка
 *
 * Расчитывает период и скважность ШИМ.
 * Направление управляется через вывод DIR.
 */
bool MotorDriver_SetVel(MotorDriver_Type *dr, int32_t vel);

/**
 * @brief Обработчик прерывания таймера
 * @param dr Указатель на структуру драйвера
 *
 * Обновляет состояние вывода направления в момент срабатывания прерывания.
 * Должна вызываться из ISR с именем, соответствующим используемому таймеру.
 */
void MotorDriver_TIMx_IRQHandler(MotorDriver_Type *dr);

#endif
